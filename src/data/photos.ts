import { API_URL, newIdempotencyKey, request } from "./http";
import { loadToken } from "../guest/session";
import { GALLERY_MAX, PHOTO_MAX_MB, type GalleryPhoto } from "./gallery";

/**
 * The shared gallery, on the server.
 *
 * It lived in localStorage, which meant every phone had its own: a photo one
 * guest shared reached nobody, and a censor the committee applied blurred the
 * tile on their own laptop and nowhere else.
 */

/** What the API returns per photo: everything but the image itself. */
type WirePhoto = {
  id: string;
  author: string;
  /** Still sent by the API; guests no longer tag or see a room on a photo. */
  roomId?: string;
  caption?: string;
  at: number;
  mine: boolean;
  censored?: boolean;
};

/**
 * Where the tile's <img> points.
 *
 * The token rides in the query string because an `<img>` tag cannot send an
 * Authorization header -- the same reason the event stream does it, and the
 * reason the server's request log records paths and never query strings.
 */
export const photoSrc = (id: string, token = loadToken()) =>
  `${API_URL}/api/photos/${encodeURIComponent(id)}/image?t=${encodeURIComponent(token ?? "")}`;

const toPhoto = (p: WirePhoto): GalleryPhoto => ({ ...p, src: photoSrc(p.id) });

export const photosApi = {
  list: async (): Promise<GalleryPhoto[]> => (await request<WirePhoto[]>("/api/photos", { token: loadToken() })).map(toPhoto),

  // No room: a photo is the guest's, not a room's (the API still accepts one, it is just never sent).
  share: async (data: string, caption: string): Promise<GalleryPhoto> =>
    toPhoto(
      await request<WirePhoto>("/api/photos", {
        method: "POST",
        token: loadToken(),
        body: { data, caption },
        // One key per photo, generated by the caller, so a retry on a weak
        // connection shares one picture rather than two.
        idempotencyKey: newIdempotencyKey(),
      }),
    ),

  remove: (id: string) => request<{ id: string }>(`/api/photos/${encodeURIComponent(id)}`, { method: "DELETE", token: loadToken() }),
};

/**
 * Shrinks a picked photo before it is uploaded.
 *
 * A phone camera writes 3–10MB per shot. Five of those from each of thirty
 * guests is well past what the database is allowed to hold, and most of it is
 * detail nobody will see on a tile or a phone-sized viewer. 1600px on the
 * long edge at JPEG 0.82 lands around 200–400KB and is still sharp
 * full-screen.
 *
 * Done here rather than on the server because the saving that matters is the
 * upload itself: the guest is on event wifi, and sending 10MB is the slow
 * part, not storing it.
 */
export async function shrink(file: File, maxEdge = 1600, quality = 0.82): Promise<string> {
  if (file.size > PHOTO_MAX_MB * 1024 * 1024) throw new Error(`Foto lebih dari ${PHOTO_MAX_MB} MB`);

  const bitmap = await createImageBitmap(file);
  try {
    const scale = Math.min(1, maxEdge / Math.max(bitmap.width, bitmap.height));
    const w = Math.max(1, Math.round(bitmap.width * scale));
    const h = Math.max(1, Math.round(bitmap.height * scale));

    const canvas = document.createElement("canvas");
    canvas.width = w;
    canvas.height = h;
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("Browser ini tidak bisa memproses foto");
    ctx.drawImage(bitmap, 0, 0, w, h);

    // JPEG, not PNG: a photo as PNG is several times larger for no gain, and
    // the server stores whatever arrives.
    return canvas.toDataURL("image/jpeg", quality);
  } finally {
    // Frees the decoded image immediately rather than at the next GC, which
    // matters when five are processed in a row on a phone.
    bitmap.close();
  }
}

export { GALLERY_MAX };
